/**
 * Imprime um icone. Sem echo de HTML dinamico: o SVG vem de um array fixo.
 */
function lv_icone( string $nome, string $classe = 'lv-icone' ): void {
	$icones = lv_icones();

	if ( ! isset( $icones[ $nome ] ) ) {
		return;
	}

	printf(
		'<svg class="%s" viewBox="0 0 24 24" width="20" height="20" fill="currentColor" aria-hidden="true" focusable="false">%s</svg>',
		esc_attr( $classe ),
		$icones[ $nome ] // phpcs:ignore WordPress.Security.EscapeOutput
	);
}

/**
 * Versao que devolve string, para usar dentro de sprintf.
 */
function lv_icone_html( string $nome, string $classe = 'lv-icone' ): string {
	ob_start();
	lv_icone( $nome, $classe );
	return (string) ob_get_clean();
}
